// Initialize Dashboard Time Greeting
const greeting = document.getElementById('greeting');
const hour = new Date().getHours();
let greetWord = 'Hello';
if(hour < 12) greetWord = 'Good morning';
else if(hour < 18) greetWord = 'Good afternoon';
else greetWord = 'Good evening';
// Add emoji matching time
const emoji = hour < 12 ? '🌅' : hour < 18 ? '☀️' : '🌙';

// Load User Data from Local Storage
const currentStudent = JSON.parse(localStorage.getItem('currentStudent')) || JSON.parse(sessionStorage.getItem('loggedInUser'));

if (currentStudent) {
    // Personalize greeting with strictly first name chunk
    const firstName = currentStudent.name.split(' ')[0];
    greeting.innerText = `${greetWord}, ${firstName}! ${emoji}`;
    
    // Dynamically Populate verified Database matches to Frontend View
    document.getElementById('stuName').innerText = currentStudent.name;
    document.getElementById('stuRoll').innerText = currentStudent.id; 
    document.getElementById('stuClass').innerText = currentStudent.class + "th Grade";
    document.getElementById('stuSection').innerText = `Section ${currentStudent.section}`;
    
    // Fetch Attendance Stats
    fetch(`/api/attendance/stats/${currentStudent.id}`)
        .then(res => res.json())
        .then(data => {
            if(data.success) {
                document.getElementById('statPresent').innerText = data.stats.present;
                document.getElementById('statAbsent').innerText = data.stats.absent;
            }
        }).catch(err => console.error(err));
        
} else {
    greeting.innerText = `${greetWord}, Student! ${emoji}`;
    // Unauthorized fallback
    window.location.href = '../auth/login.html';
}

// Attendance feature
document.getElementById('btnAttendance').addEventListener('click', async () => {
    const code = prompt("Please enter the attendance secret code generated by your teacher:");
    if (code && currentStudent) {
        try {
            const res = await fetch('/api/attendance/mark', {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ studentId: currentStudent.id, code: code.trim() })
            });
            const data = await res.json();
            
            if(data.success) {
                alert("✅ Attendance verified correctly and status recorded as Present!");
                window.location.reload(); // Refresh to catch new stat numbers
            } else {
                alert("❌ Cannot mark attendance: " + data.message);
            }
        } catch(e) {
            console.error("Attendance Update Error:", e);
            alert("Network error processing attendance.");
        }
    } else if (!currentStudent) {
        alert("Invalid user session. Please log in.");
    }
});

